/**
 * Regenerate `src/latex.js` from the renderer dsh-tui vendors.
 *
 * hncode has no dependencies, so the TeX parser cannot be a package: it is vendored as plain JavaScript.
 * The source of truth is `D:\dsh-tui\src\terminal-utils\latex.ts` (itself Pi's renderer, MIT), and this
 * script does the three mechanical things that turn it into this repo's module — strip the types with
 * Node's own stripper, point the width helper at `src/term.js`, and append the exports this project uses.
 * Nothing in the parser is hand-edited, so a re-run after an upstream change is a plain diff.
 *
 *   node tools/build-latex.mjs
 */
import fs from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';

const SRC = 'D:/dsh-tui/src/terminal-utils/latex.ts';
const OUT = 'src/latex.js';

const stripped = stripTypeScriptTypes(fs.readFileSync(SRC, 'utf8'), { mode: 'strip' });

/** Pi's vendoring header, kept: it ends with the MIT text this file has to carry. */
const licenseAt = stripped.indexOf(' * MIT License');
const licenseEnd = stripped.indexOf(' */', licenseAt);
if (licenseAt < 0 || licenseEnd < 0) throw new Error('license block not found');
const license = stripped
  .slice(licenseAt + 2, licenseEnd)
  .split('\n')
  .map((line) => line.replace(/\s+$/, ''))
  .join('\n')
  .trim();

let code = stripped.slice(licenseEnd + 3);

// The width helper: Pi's is `stringWidth` from its Ink fork, this project's is `visualWidth` in term.js.
code = code.replace(
  'import { stringWidth as visibleWidth } from "../ink/stringWidth.js";',
  'import { visualWidth as visibleWidth } from "./term.js";',
);
if (code.includes('../ink/stringWidth.js')) throw new Error('width import not replaced');

/**
 * Remove the gaps type stripping leaves behind.
 *
 * `function f(a: string, b: string)` becomes `function f(a        , b        )`, because only the type
 * annotations are removed. The result parses, but every signature and call carries a column of dead space
 * that makes the vendored file read as damaged. Runs of spaces are collapsed OUTSIDE string literals, and
 * trailing whitespace is dropped, which leaves the code formatted as its author wrote it.
 */
const LITERAL = /("(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*'|`(?:[^`\\]|\\.)*`)/;
function tidy(text) {
  return text.split('\n').map((line) => {
    const parts = line.split(LITERAL);
    // Odd indices are the literals; even ones are code and may be collapsed.
    const joined = parts.map((part, i) => (i % 2 === 1 ? part : part.replace(/ {2,}/g, ' '))).join('');
    return joined.replace(/[ \t]+$/, '');
  }).join('\n');
}

code = tidy(code).replace(/^\s+/, '').replace(/\s+$/, '');

const header = `/**
 * LaTeX math -> terminal Unicode text.
 *
 * A TeX subset rendered as text: symbols, scripts, stacked fractions, roots, operator limits, matrices,
 * cases, aligned rows and accents. The layout is real geometry, not a flattened one-liner: a fraction is
 * three rows, and in display mode a sum carries its limits above and below.
 *
 * This is the text renderer. A terminal that can show a bitmap gets the TYPESET version instead
 * (\`src/tex/\`), and this one is the fallback for one that cannot.
 *
 * \`renderLatex\` returns undefined when the source is outside the subset or malformed; the caller then shows
 * the ORIGINAL text, because a half-rendered formula reads worse than the formula and the reader may want
 * the TeX.
 *
 * VENDORED — do not edit this file. It is generated by \`tools/build-latex.mjs\` from
 * \`D:/dsh-tui/src/terminal-utils/latex.ts\`, which is Pi's renderer (packages/tui/src/latex.ts, MIT,
 * Copyright (c) 2025 Mario Zechner). Only the imports and the two exports below are this project's.
 */

/*
${license}
 */

${code}

/**
 * TeX command -> Unicode table.
 *
 * Exported because the bitmap renderer (\`src/tex/parse.js\`) shares it: a formula drawn as pixels must map a
 * command to the same character the text renderer picks, or the two disagree about what a name looks like.
 */
export { SYMBOLS };
`;

fs.writeFileSync(OUT, header, 'utf8');
console.log('wrote', OUT, header.length, 'bytes');
