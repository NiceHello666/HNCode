/**
 * Look up one key. `lang` is a language id; anything unknown falls back to the
 * default, then to English, then to the key itself (which makes a missing string
 * obvious in situ instead of rendering as `undefined`).
 */
export function t(lang, key, vars) {
  const entry = MESSAGES[key];
  if (!entry) return key;
  let s = entry[lang] || entry[DEFAULT_LANG] || entry.en || key;
  if (vars) {
    for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
  }
  return s;
}

/**
 * Look up a string that may be TRANSLATED-OR-NOT, returning `fallback` when there is no
 * entry for this language.
 *
 * This is what the terminal UI uses. A command's English description lives beside the
 * command in tui.js, where it is read by whoever maintains the command — copying it into
 * MESSAGES as well would make two copies that drift. So the table holds only the
 * translations, and an untranslated string comes back from the code itself.
 *
 * `undefined` is returned only when there is nothing to say in either place, which lets a
 * caller distinguish "not translated" from "no text at all".
 */
export function tOr(lang, key, fallback) {
  const entry = MESSAGES[key];
  if (!entry || !entry[lang]) return fallback;
  return entry[lang];
}

