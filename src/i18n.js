// The UI's active language, shared with the render modules (rows, panels, file tree)
// that draw strings which are not notices and have no tui.js key at their call site.
// tui.js's setUiLang updates this; a getter keeps every renderer on the same source.
let uiLang = 'en';
export function setUiLang(lang) { uiLang = lang === 'zh' ? 'zh' : 'en'; }
export function getUiLang() { return uiLang; }

/** Translate a line rendered OUTSIDE tui.js using the UI's active language. */
export function uiText(text) {
  const s = String(text == null ? '' : text);
  if (uiLang !== 'zh') return s;
  // Direct hit first — the common case for fixed labels.
  if (NOTICE_ZH[s]) return NOTICE_ZH[s];
  // Numbers and quoted values vary; normalise both to placeholders and look up the
  // pattern. The translation carries the same placeholders, filled back with the
  // originals in order.
  const vars = [];
  const key = s
    .replace(/"[^"]*"/g, (m) => { vars.push(m); return '{s}'; })
    .replace(/\d+/g, (m) => { vars.push(m); return '{n}'; });
  const pattern = NOTICE_ZH[key];
  if (!pattern) return s;
  let i = 0;
  return pattern.replace(/\{[sn]\}/g, () => vars[i++] || '');
}

/** Translate a final, non-templated notice string. Unknown text comes back unchanged. */
export function noticeText(lang, text) {
  if (lang !== 'zh') return text;
  return NOTICE_ZH[text] || text;
}

/** The whole table for one language, as a flat { key: string } map. */
export function catalog(lang) {
  const out = {};
  for (const key of Object.keys(MESSAGES)) out[key] = t(lang, key);
  return out;
}
